// Four manually selected units: 0/1 = K3(+DW3), 2/3 = ordinary K1.
// No task RAM, frame PCs, dependency graph, lease manager or automatic picker.
// Software owns addresses, dependencies and buffer lifetimes.
module cnn_simple_top #(parameter integer MAX_CHANNELS=512, parameter bit BURST_READ=1, parameter bit READ64=1, parameter bit BULK=READ64, parameter bit PACKED_WRITE=1,
 parameter integer WRITE_BITS=256,
 parameter bit K3_FIFO=1, K1_EXTRA=1)(
 input wire clk,rst_n,memory_fault,
 input wire [31:0] mmio_addr,mmio_wdata,input wire mmio_re,mmio_we,
 output logic [31:0] mmio_rdata,output wire mmio_ready,
 output wire [3:0] mem_valid,mem_write,mem_byte,mem_double,mem_wide,
 output wire [127:0] mem_addr,
 output wire [4*WRITE_BITS-1:0] mem_wdata,
 input wire [3:0] mem_ready,mem_response,input wire [255:0] mem_rdata,
 output wire [3:0] unit_busy,unit_done,unit_error,unit_work,
 output wire busy,done,error,
 output wire [15:0] operator_phase,output wire [11:0] memory_phase,
 output wire [3:0] span_accept,span_weight,output wire [51:0] span_bytes,
 output wire [127:0] mac_counts
);
 logic [31:0] descriptor[0:3][0:15];
 logic [3:0] start_q,abort_q,done_q,error_q;
 logic [31:0] error_code[0:3],completed[0:3];
 wire [3:0] core_busy,core_done,core_error,bridge_busy;
 wire [3:0] cv,cw,cb,cr,cp;
 wire [127:0] ca,cd;
 localparam integer UPPER=WRITE_BITS-32;
 wire [4*UPPER-1:0] cd_upper;
 wire [3:0] c_wide;
 wire [255:0] cdata;
 wire [3:0] c_double;
 wire [3:0] addressed;
 assign mmio_ready=1;
 assign unit_busy=core_busy|bridge_busy|start_q|abort_q;
 assign unit_done=done_q;assign unit_error=error_q;
 assign busy=|unit_busy;assign done=|done_q;assign error=|error_q;
 for(genvar u=0;u<4;u++)begin:unit
  // Explicit page decode; there is no modulo, variable client selection or
  // combinational global cancel generated by another operator's status.
  assign addressed[u]=mmio_addr[31:8]==24'(u+1);
  always_ff @(posedge clk)begin
   if(!rst_n)begin
    start_q[u]<=0;abort_q[u]<=0;done_q[u]<=0;error_q[u]<=0;
    error_code[u]<=0;completed[u]<=0;
    for(integer w=0;w<16;w++)descriptor[u][w]<=0;
   end else begin
    start_q[u]<=0;
    if(abort_q[u] && !core_busy[u] && !bridge_busy[u] && !start_q[u])abort_q[u]<=0;
    if(core_done[u] && !abort_q[u])begin done_q[u]<=1;completed[u]<=completed[u]+1'b1;end
    if(core_error[u] && !abort_q[u])begin error_q[u]<=1;error_code[u]<=1;end
    if(mmio_we && addressed[u])begin
     if(mmio_addr[7:0]==0)case(mmio_wdata)
      1:if(!unit_busy[u])begin start_q[u]<=1;done_q[u]<=0;error_q[u]<=0;error_code[u]<=0;end
        else begin error_q[u]<=1;error_code[u]<=2;end
      2:begin done_q[u]<=0;error_q[u]<=0;error_code[u]<=0;end
      4:begin abort_q[u]<=1;done_q[u]<=0;error_q[u]<=1;error_code[u]<=3;end
      default:begin error_q[u]<=1;error_code[u]<=4;end
     endcase
     else if(mmio_addr[7:0]>=8'h20 && mmio_addr[7:0]<8'h60 && mmio_addr[1:0]==0)begin
      if(!unit_busy[u])descriptor[u][mmio_addr[5:2]-4'd8]<=mmio_wdata;
      else begin error_q[u]<=1;error_code[u]<=2;end
     end else begin error_q[u]<=1;error_code[u]<=4;end
    end
    if(memory_fault)begin abort_q[u]<=1;error_q[u]<=1;error_code[u]<=5;done_q[u]<=0;end
   end
  end
  wire [12:0] read_span;
  wire read_lock,write_drained;
  if(u<2)begin:k3
   assign c_double[u]=0;
   assign c_wide[u]=0;
   assign cd_upper[u*UPPER+:UPPER]=0;
   simple_k3_engine #(.MAX_CHANNELS(MAX_CHANNELS),.BACKGROUND_WRITE(K3_FIFO && BURST_READ)) engine(
    .clk,.rst_n,.clear(abort_q[u]),.start(start_q[u]),.depthwise(descriptor[u][8][0]),
    .input_base(descriptor[u][0]),.weight_base(descriptor[u][1]),.output_base(descriptor[u][2]),
    .width(descriptor[u][3]),.height(descriptor[u][4]),.in_channels(descriptor[u][5]),
    .out_channels(descriptor[u][6]),.kernel(32'd3),.stride(descriptor[u][7]),
    .plan_flags(descriptor[u][13]),.plan_input_row_bytes(descriptor[u][9]),
    .plan_weight_per_channel(descriptor[u][10]),.plan_input_extent(descriptor[u][11]),.plan_weight_extent(descriptor[u][12]),
    .busy(core_busy[u]),.done(core_done[u]),.error(core_error[u]),.valid(cv[u]),.write(cw[u]),.byte_access(cb[u]),
    .addr(ca[u*32+:32]),.wdata(cd[u*32+:32]),.ready(cr[u]),.response(cp[u]),.write_drained,.rdata(cdata[u*64+:32]),
    .read_span,.reading_weights(span_weight[u]),.mac_fire(unit_work[u]),.phase(operator_phase[u*4+:4]),.input_reads(),.weight_reads(),.mac_count(mac_counts[u*32+:32]));
  end else begin:k1
   simple_k1_engine #(.BURST_READ(BURST_READ),.READ64(READ64),.BULK(BULK),.PACKED_WRITE(PACKED_WRITE),.WRITE_BITS(WRITE_BITS),.MAX_CHANNELS(MAX_CHANNELS),.OUTPUT_PAR(1),.INPUT_PREFETCH(0),.READ_AHEAD(0),.EXTRA_RESULTS(K1_EXTRA)) engine(
    .read_lock,.write_wide(c_wide[u]),.write_upper(cd_upper[u*UPPER+:UPPER]),.read_double(c_double[u]),.read_upper(cdata[u*64+32+:32]),.clk,.rst_n,.clear(abort_q[u]),.start(start_q[u]),.depthwise(descriptor[u][8][0]),
    .input_base(descriptor[u][0]),.weight_base(descriptor[u][1]),.output_base(descriptor[u][2]),
    .width(descriptor[u][3]),.height(descriptor[u][4]),.in_channels(descriptor[u][5]),
    .out_channels(descriptor[u][6]),.kernel(32'd1),.stride(descriptor[u][7]),
    .busy(core_busy[u]),.done(core_done[u]),.error(core_error[u]),.valid(cv[u]),.write(cw[u]),.byte_access(cb[u]),
    .addr(ca[u*32+:32]),.wdata(cd[u*32+:32]),.ready(cr[u]),.response(cp[u]),.rdata(cdata[u*64+:32]),
    .read_span,.reading_weights(span_weight[u]),.mac_fire(unit_work[u]),.phase(operator_phase[u*4+:4]),.input_reads(),.weight_reads(),.mac_count(mac_counts[u*32+:32]));
  end
  if(BURST_READ)begin:long_reads
   wire cmd_valid,cmd_ready,data_valid,data_ready,data_last,reader_busy;
   wire [3:0] data_bytes;
   wire [12:0] cmd_bytes;
   wire read_busy,write_busy,read_ready,write_ready,read_response,write_response;
   wire rv,rb,rdouble,wv,ww,wb,wwide;
   wire [31:0] ra,wa;
   wire [WRITE_BITS-1:0] wd;
   wire [63:0] rd;
   wire [2:0] read_phase,write_phase;
   assign bridge_busy[u]=read_busy || write_busy;
   wire feed_read,feed_write,feed_wide;
   wire [31:0] feed_addr;
   wire [WRITE_BITS-1:0] feed_data;
   if(u<2 && K3_FIFO)begin:buffered_result
    wire available,space,empty;
    wire [63:0] result;
    logic prefer_write;
    wire want_read=cv[u] && !cw[u];
    wire choose_write=available && !read_busy && (write_busy || prefer_write || !want_read);
    assign feed_read=want_read && !write_busy && (read_busy || !choose_write);
    assign feed_write=choose_write;
    assign feed_wide=0;
    assign feed_addr=result[63:32];
    assign feed_data={{UPPER{1'b0}},result[31:0]};
    assign cr[u]=read_ready || (cv[u] && cw[u] && space);
    assign cp[u]=read_response || (cv[u] && cw[u] && space);
    assign write_drained=empty && !write_busy;
    always_ff @(posedge clk)begin
     if(!rst_n || abort_q[u])prefer_write<=0;
     else if(!read_busy && !write_busy && (feed_read || feed_write))
      prefer_write<=feed_read;
    end
    k3_result_fifo results(
     .clk,.rst_n,.clear(abort_q[u]),.push(cv[u] && cw[u]),.item({ca[u*32+:32],cd[u*32+:32]}),
     .space,.empty,.valid(available),.head(result),.pop(write_response));
   end else begin:direct_result
    assign feed_read=cv[u] && !cw[u] && !write_busy;
    assign feed_write=cv[u] && cw[u] && !read_busy;
    assign feed_wide=PACKED_WRITE && c_wide[u];
    assign feed_addr=ca[u*32+:32];
    assign feed_data={cd_upper[u*UPPER+:UPPER],cd[u*32+:32]};
    assign cr[u]=read_ready || write_ready;
    assign cp[u]=read_response || write_response;
    assign write_drained=1;
   end
   assign cdata[u*64+:64]=rd;
   assign memory_phase[u*3+:3]=write_busy ? write_phase : read_phase;
   assign mem_valid[u]=rv || wv;
   assign mem_write[u]=wv && ww;
   assign mem_double[u]=!write_busy && rdouble;
   assign mem_byte[u]=write_busy ? wb : rb;
   assign mem_addr[u*32+:32]=write_busy ? wa : ra;
   assign mem_wdata[u*WRITE_BITS+:WRITE_BITS]=wd;
   assign mem_wide[u]=write_busy && wwide;
   simple_mem_bridge #(.DATA_BITS(WRITE_BITS)) write_port(.clk,.rst_n,.abort(abort_q[u]),
    .c_valid(feed_write),.c_write(1'b1),.c_byte(1'b0),.c_wide(feed_wide),
    .c_addr(feed_addr),.c_wdata(feed_data),.c_ready(write_ready),
    .c_response(write_response),.c_rdata(),.busy(write_busy),.phase(write_phase),
    .m_valid(wv),.m_write(ww),.m_byte(wb),.m_wide(wwide),.m_addr(wa),.m_wdata(wd),
    .m_ready(mem_ready[u]),.m_response(mem_response[u] && write_busy),.m_rdata(32'd0));
   wire [31:0] cmd_addr;
   wire [63:0] data;
   assign span_accept[u]=cmd_valid && cmd_ready;
   assign span_bytes[u*13+:13]=cmd_bytes;
   conv_span_port client(.clk,.rst_n,.abort(abort_q[u]),.c_valid(feed_read),.c_byte(cb[u]),.c_double(c_double[u]),
    .c_addr(ca[u*32+:32]),.c_span(read_span),
    .c_ready(read_ready),.c_response(read_response),.c_rdata(rd),
    .busy(read_busy),.read_lock,.phase(read_phase),
    .cmd_valid,.cmd_ready,.cmd_addr,.cmd_bytes,
    .reader_busy,.data_valid,.data_ready,.data_bytes,.data_last,.data);
   bank_span_reader #(.READ64(READ64)) reader(.clk,.rst_n,.abort(abort_q[u]),.busy(reader_busy),
    .cmd_valid,.cmd_ready,.cmd_addr,.cmd_bytes,
    .data_valid,.data_ready,.data_bytes,.data_last,.data,
    .m_valid(rv),.m_byte(rb),.m_double(rdouble),.m_addr(ra),
    .m_ready(mem_ready[u]),.m_response(mem_response[u] && !write_busy),.m_rdata(mem_rdata[u*64+:64]));
  end else begin:single_reads
   assign write_drained=1;
   assign cdata[u*64+32+:32]=0;assign mem_double[u]=0;
   assign mem_wdata[u*WRITE_BITS+32+:UPPER]=0;assign mem_wide[u]=0;
   assign read_lock=0;assign span_accept[u]=0;assign span_bytes[u*13+:13]=0;
   simple_mem_bridge port(
   .clk,.rst_n,.abort(abort_q[u]),.c_valid(cv[u]),.c_write(cw[u]),.c_byte(cb[u]),.c_wide(1'b0),.c_addr(ca[u*32+:32]),.c_wdata(cd[u*32+:32]),
   .c_ready(cr[u]),.c_response(cp[u]),.c_rdata(cdata[u*64+:32]),
   .m_valid(mem_valid[u]),.m_write(mem_write[u]),.m_byte(mem_byte[u]),.m_wide(),.m_addr(mem_addr[u*32+:32]),.m_wdata(mem_wdata[u*WRITE_BITS+:32]),
   .m_ready(mem_ready[u]),.m_response(mem_response[u]),.m_rdata(mem_rdata[u*64+:32]),.busy(bridge_busy[u]),.phase(memory_phase[u*3+:3]));
  end
 end
 always_comb begin
  mmio_rdata=0;
  if(mmio_re)begin
   case(mmio_addr)
    0:mmio_rdata=32'h53434e31;
    4:mmio_rdata={20'd0,error_q,done_q,unit_busy};
    8:mmio_rdata=32'h00000202;
    default:for(integer u=0;u<4;u++)if(addressed[u])begin
     case(mmio_addr[7:0])
      4:mmio_rdata={28'd0,abort_q[u],error_q[u],done_q[u],unit_busy[u]};
      8:mmio_rdata=error_code[u];
      12:mmio_rdata=completed[u];
      16:mmio_rdata={25'd0,memory_phase[u*3+:3],operator_phase[u*4+:4]};
      20:mmio_rdata=mac_counts[u*32+:32];
      default:if(mmio_addr[7:0]>=8'h20 && mmio_addr[7:0]<8'h60 && mmio_addr[1:0]==0)
       mmio_rdata=descriptor[u][mmio_addr[5:2]-4'd8];
     endcase
    end
   endcase
  end
 end
endmodule
