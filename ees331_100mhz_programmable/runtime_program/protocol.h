#ifndef EES331_PROGRAM_PROTOCOL_H
#define EES331_PROGRAM_PROTOCOL_H
#include <stdint.h>

#define EES331_GP0_BASE 0x40000000u
#define EES331_REQUEST 0x08u
#define EES331_ACK 0x0cu
#define EES331_COMMAND 0x10u
#define EES331_ARGS 0x14u
#define EES331_REPLY_STATUS 0x50u
#define EES331_REPLY_DATA 0x54u
#define EES331_CPU_READY 0x64u
#define EES331_EXEC_TASK 1u
#define EES331_CACHE_SYNC 2u
#define EES331_DDR_BASE 0x10000000u
#define EES331_DDR_BYTES 0x01000000u
#define EES331_READY_VALUE 0x52563332u
#define EES331_PROGRAM_CONTROL 0x100u
#define EES331_PROGRAM_EPOCH 0x104u
#define EES331_PROGRAM_COUNTS 0x108u
#define EES331_IMEM_WINDOW 0x2000u
#define EES331_DMEM_WINDOW 0x4000u
#define EES331_IMEM_BYTES 8192u
#define EES331_DMEM_BYTES 16384u
#define EES331_DATA_START 8192u
#define EES331_IMAGE_MAGIC 0x31505652u
#define EES331_IMAGE_MAX_DATA (EES331_DMEM_BYTES - EES331_DATA_START)
#define EES331_RV_NOP 0x00000013u
#define EES331_TASK_ARGS 14u
#define EES331_RESULT_WORDS 4u

enum ees331_program_control { EES331_DRAIN = 1, EES331_CANCEL = 2,
                             EES331_BEGIN = 4, EES331_START = 8 };
enum ees331_task_status { EES331_TASK_OK = 0, EES331_TASK_CANCELLED = 1,
                         EES331_TASK_INVALID = 2 };
enum ees331_task_state { EES331_EMPTY = 0, EES331_QUEUED, EES331_RUNNING,
                         EES331_DONE, EES331_CANCELLED, EES331_FAILED };

#endif
