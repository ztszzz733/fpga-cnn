"""Generate explicit six-peer RTL wiring from the reviewed draw.io manifest.

The diagram is a frozen design input. This generator never rewrites it.
EES331_EXTERNAL_PS exposes PS-facing ports for RTL verification only.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'deliverables/ees331_ddr_io/io_manifest.json'


def signals(link):
    return [s for group in ('address', 'data', 'control') for s in link[group]]


def declaration(kind, name, width):
    return f"{kind} {'['+str(width-1)+':0] ' if width > 1 else ''}{name}"


def main():
    links = {e['id']: e for e in json.loads(MANIFEST.read_text(encoding='utf-8'))['after']}
    local = ['I', 'D', 'M0', 'M1', 'C', 'F']
    physical = signals(links['B']) + [dict(name=n, width=w) for n,w in (
        ('DDR_VRN',1),('DDR_VRP',1),('FIXED_IO_MIO',54),('FIXED_IO_PS_CLK',1),
        ('FIXED_IO_PS_PORB',1),('FIXED_IO_PS_SRSTB',1))]
    ps = []
    for group in ['G','H']:
        for s in signals(links[group]):
            # GP source is PS; HP target is PS.
            out = (s['direction'] == 'rev') if group == 'G' else (s['direction'] == 'fwd')
            ps.append((s['name'],s['width'],'output wire' if out else 'input wire'))
    lines = ['// Generated by scripts/gen_ees331_top.py. Peer wiring follows draw.io pages 02-07.',
             '// Hardware build has six PL peers plus PS7. No PL DDR PHY or PL UART.',
             'module face_soc_ees331_top #(',
             ' parameter integer CACHE_BYTES=131072,',
             ' parameter string IMEM_INIT_FILE="firmware/ees331_cpu/program.mem"',
             ') (', '`ifdef EES331_EXTERNAL_PS',
             ' input wire FCLK_CLK0, FCLK_RESET0_N,',
             ' output wire M_AXI_GP0_ACLK, S_AXI_HP0_ACLK,']
    lines += [' '+declaration(d,n,w)+(',' if i<len(ps)-1 else '') for i,(n,w,d) in enumerate(ps)]
    lines += ['`else']
    lines += [' '+declaration('inout wire',s['name'],s['width'])+(',' if i<len(physical)-1 else '') for i,s in enumerate(physical)]
    lines += ['`endif', ');', ' wire clk, rst_n;', ' wire sys_clk, rst_n_in;']
    for group in local:
        lines.append(f" // {group}: {links[group]['title']}")
        lines += [' '+declaration('wire',s['name'],s['width'])+';' for s in signals(links[group])]
    lines += ['`ifndef EES331_EXTERNAL_PS', ' wire FCLK_CLK0, FCLK_RESET0_N;',
              ' wire M_AXI_GP0_ACLK, S_AXI_HP0_ACLK;']
    lines += [' '+declaration('wire',n,w)+';' for n,w,_ in ps]
    lines += ['`endif',
              ' assign sys_clk=FCLK_CLK0;', ' assign rst_n_in=FCLK_RESET0_N;',
              ' assign M_AXI_GP0_ACLK=clk;', ' assign S_AXI_HP0_ACLK=clk;',
              ' clock_unit u_clock_unit (.sys_clk(sys_clk),.rst_n_in(rst_n_in),.clk(clk),.rst_n(rst_n));']
    def instance(module, name, groups, parameters=''):
        ports=['clk','rst_n']+[s['name'] for g in groups for s in signals(links[g])]
        lines.append(f' {module} {parameters} {name} (')
        lines.extend('  .'+n+'('+n+')'+(',' if i<len(ports)-1 else '') for i,n in enumerate(ports))
        lines.append(' );')
    instance('cpu_core','u_cpu_core',['I','D','M0'],
             "#(.SRAM_BASE(32'h0),.SRAM_SIZE(32'h4000),.CNN_MMIO_BASE(32'h40000000))")
    instance('imem_rom','u_imem',['I'],"#(.IMEM_SIZE(32'h2000),.INIT_FILE(IMEM_INIT_FILE))")
    instance('cnn_ees331','u_cnn',['M1','C'])
    instance('datasram_ddr_subsystem','u_datasram',['D','C','F','H'],
             '#(.CACHE_BYTES(CACHE_BYTES),.CPU_RAM_BYTES(16384))')
    instance('image_control_bridge','u_image_bridge',['M0','M1','F','G'])
    lines += ['`ifndef EES331_EXTERNAL_PS',
              ' // PS UART1 TX/RX use existing MIO48/49 to J3, not new PL wires.',
              ' // HP issue capability defaults: normal buffering, no forced single issue.',
              ' ees331_ps_wrapper u_ps (']
    pnames=[s['name'] for s in physical]+['FCLK_CLK0','FCLK_RESET0_N','M_AXI_GP0_ACLK','S_AXI_HP0_ACLK']+[n for n,_,_ in ps]
    lines += ['  .'+n+'('+n+'),' for n in pnames]
    lines += ["  .S_AXI_HP0_RDISSUECAP1_EN(1'b0),", "  .S_AXI_HP0_WRISSUECAP1_EN(1'b0),",
              '  .S_AXI_HP0_RCOUNT(),.S_AXI_HP0_WCOUNT(),.S_AXI_HP0_RACOUNT(),.S_AXI_HP0_WACOUNT()',
              ' );','`endif','endmodule','']
    target=ROOT/'rtl/soc/ees331/face_soc_ees331_top.sv'
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text('\n'.join(lines),encoding='utf-8')
    print(target)


if __name__=='__main__':
    main()
